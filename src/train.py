"""King County Model Training, Hyperparameter Tuning, and Persistence Module.

This module loads the preprocessed dataset, executes a leakage-free train/test
split, builds a scikit-learn pipeline featuring polynomial expansion, target transformation,
and ElasticNet regression, optimizes hyperparameters using GridSearchCV, and persists
the trained model using skops.
"""

from pathlib import Path
import pandas as pd
from sklearn.compose import TransformedTargetRegressor
from sklearn.linear_model import ElasticNet
from sklearn.model_selection import GridSearchCV, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import PolynomialFeatures, StandardScaler
import skops.io as sio


def train_and_save_model(data_path: Path, model_output_path: Path):
    """Loads preprocessed data, trains the regression pipeline, and persists the model artifact.

    Args:
        data_path (Path): Path to the preprocessed CSV file generated by the pipeline.
        model_output_path (Path): Path where the binary model artifact (.bin) will be saved.

    Returns:
        Best trained scikit-learn estimator from GridSearchCV.
    """
    print(f"[1/5] Loading preprocessed dataset from: {data_path}")
    df = pd.read_csv(data_path)

    # Columns causing data leakage or non-predictive identifiers
    potential_drop_columns = [
        "price",
        "sqft_price",
        "date",
        "delta_lat",
        "delta_long",
        "id",
    ]
    drop_columns = [col for col in potential_drop_columns if col in df.columns]
    feature_columns = [col for col in df.columns if col not in drop_columns]

    X = df[feature_columns]
    y = df["price"]

    print("[2/5] Performing train/test split (70% Train / 30% Test)...")
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.3, random_state=42
    )

    print("[3/5] Configuring scikit-learn Pipeline with ElasticNet...")
    pipeline = Pipeline(
        [
            ("polynomial", PolynomialFeatures(degree=2, include_bias=False)),
            ("scaler", StandardScaler()),
            (
                "model",
                TransformedTargetRegressor(
                    regressor=ElasticNet(max_iter=5000, tol=1e-4),
                    transformer=StandardScaler(),
                ),
            ),
        ]
    )

    # Hyperparameter grid search specification
    param_grid = {
        "model__regressor__alpha": [0.01, 0.1, 1.0],
        "model__regressor__l1_ratio": [0.2, 0.5, 0.8],
    }

    grid_search = GridSearchCV(
        pipeline, param_grid, cv=5, scoring="r2", n_jobs=-1, verbose=1
    )

    print("[4/5] Executing 5-fold cross-validation grid search...")
    grid_search.fit(X_train, y_train)

    best_model = grid_search.best_estimator_
    test_score = best_model.score(X_test, y_test)

    print(f"Optimal hyperparameters: {grid_search.best_params_}")
    print(f"Test Set R^2 Score: {test_score:.4f}")

    print(f"[5/5] Exporting trained model artifact using skops to: {model_output_path}")
    model_output_path.parent.mkdir(parents=True, exist_ok=True)
    sio.dump(best_model, model_output_path)

    print("Model artifact successfully created and saved.")
    return best_model


if __name__ == "__main__":
    # Resolve project root directory dynamically
    # Path(__file__) -> king_county_project/src/train.py
    # .parent        -> king_county_project/src/
    # .parent.parent -> king_county_project/ (Project Root)
    PROJECT_ROOT = Path(__file__).resolve().parent.parent

    # Input dataset path
    DATA_PATH = (
        PROJECT_ROOT / "data" / "King_County_House_prices_pipeline_output.csv"
    )

    # Output model binary path
    MODEL_PATH = PROJECT_ROOT / "model" / "model.bin"

    train_and_save_model(data_path=DATA_PATH, model_output_path=MODEL_PATH)